-- 클라우드 수집 재개 (jobid 1) — 20분 → 5분.
--
-- 배경: 2026-08-12 에 "카카오가 클라우드 IP 를 막는다"고 판단해 이 크론을 껐고, 수집을
-- 담당자 기기 launchd 로 옮겼다. 그 판단은 **틀렸다.**
--
-- 2026-08-13 재측정(scripts/kakao-cloud-ip-test.mjs — 갓 뽑은 쿠키를 기기·클라우드에서
-- 거의 동시에 사용):
--     기기 (호출 전)        me=200 chats=200
--     클라우드 (Supabase)   me=200 _VGAQn=200 _rcpPG=200
--     기기 (호출 후)        me=200 chats=200
-- 이어서 kakao-collect Edge Function 을 실제로 호출해 LIVE 채널 101건 적재까지 확인했다.
-- 즉 막힌 것은 IP 가 아니라 **보관함 쿠키가 이미 낡아 있었던 것**이었다. 8-12 의 실측은
-- 두 호출 사이에 4분이 있었고, 그 사이 기기 Chrome 이 세션 토큰을 굴려 스냅샷이 무효가 됐다.
--
-- 새 구조:
--   · 수집    = 클라우드(이 크론, 5분)      ← 기기가 자든 말든 돈다
--   · 쿠키갱신 = 담당자 기기(launchd, 30분)  ← Chrome 로그인 세션이 있는 유일한 곳
--   기기 launchd 의 수집 잡은 기본 설치에서 뺀다(중복 호출 방지). 되살리려면
--   `bash scripts/install-launchd.sh --with-local-collect`.
--
-- ⚠️ 완전한 기기 독립은 아니다. 기기가 오래 꺼져 있으면 쿠키가 갱신되지 않아 결국 만료된다.
--    다만 "뚜껑 닫으면 즉시 수집 중단" 은 사라진다 — 쿠키가 살아 있는 동안은 계속 수집한다.
--    쿠키가 갱신 없이 얼마나 버티는지는 아직 미측정. 알럿봇이 만료를 잡아 알린다.

select cron.alter_job(1, schedule := '*/5 * * * *', active := true);
