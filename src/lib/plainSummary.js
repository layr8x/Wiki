// src/lib/plainSummary.js
// 카드 요약문에서 마크다운 표기를 걷어낸다.
//
// 왜 필요한가: 가이드 본문은 마크다운으로 쓰는데, 목록 카드의 요약(tldr)은 그 문장을
// 그대로 잘라 쓴다. 카드에서는 마크다운을 렌더하지 않으므로 표기 문자가 화면에 그대로
// 남는다. 실제로 목록에 이렇게 떠 있었다.
//
//   "신한캠퍼스(신캠) 결제는 일반 PG/VAN 과 달리 **부분환불 불가** · **분할결제 불가** ..."
//
// 별표가 강조가 아니라 글자로 보이니, 읽는 사람은 오타나 깨진 문자로 받아들인다.
// 여기서는 표기만 벗기고 글자는 그대로 둔다(강조하려던 낱말은 남는다).
//
// 본문 렌더러를 대신하려는 게 아니다. 카드 한 줄 요약에서 자주 나오는 표기만 다룬다.

const RULES = [
  // 코드 표기 `...` → 안쪽 글자만. 링크보다 먼저 지워야 링크 규칙이 안 엉킨다.
  [/`([^`]+)`/g, '$1'],
  // 이미지 ![대체문구](주소) → 대체문구. 링크 규칙보다 먼저 와야 한다.
  [/!\[([^\]]*)\]\([^)]*\)/g, '$1'],
  // 링크 [글자](주소) → 글자
  [/\[([^\]]+)\]\([^)]*\)/g, '$1'],
  // 굵게/기울임 ***,**,*,___,__,_ → 안쪽 글자만
  [/\*{1,3}([^*]+)\*{1,3}/g, '$1'],
  [/_{1,3}([^_]+)_{1,3}/g, '$1'],
  // 취소선 ~~글자~~
  [/~~([^~]+)~~/g, '$1'],
  // 줄머리 표기: 제목(#), 인용(>), 목록(-,*,+), 번호목록
  [/^\s{0,3}#{1,6}\s+/gm, ''],
  [/^\s{0,3}>\s?/gm, ''],
  [/^\s{0,3}[-*+]\s+/gm, ''],
  [/^\s{0,3}\d+\.\s+/gm, ''],
]

/**
 * 마크다운 표기를 걷어낸 한 줄 요약.
 * 값이 없으면 빈 문자열(카드가 undefined 를 그리지 않도록).
 */
export function plainSummary(text) {
  if (typeof text !== 'string' || text === '') return ''
  let out = text
  for (const [re, to] of RULES) out = out.replace(re, to)
  // 표기를 지우면서 생긴 연속 공백·줄바꿈을 한 칸으로 모은다
  return out.replace(/\s+/g, ' ').trim()
}
