#!/usr/bin/env node
/*
 * scripts/build-guide-index.mjs — AI 검색용 통합 가이드 인덱스 생성기.
 *
 * 위키 검색이 보던 GUIDES(수십 개)뿐 아니라, 검색에서 빠져 있던 AMS 가이드(100)·
 * 공식 Q&A(officialQa)·매니저 FAQ(managerFaq)까지 전부 합쳐 가벼운 인덱스
 * [{ id, title, tldr, module, type, route }] 로 만들어 api/_lib/guide-index.json 에 쓴다.
 * api/ai-search.js 가 이 인덱스를 근거로 Claude 가 "의미로" 관련 문서를 찾고 답하게 한다.
 *
 * 콘텐츠가 바뀌면 다시 실행: npm run build:guide-index  (배포 전 prebuild 로도 자동 실행)
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const { GUIDES } = await import(resolve(ROOT, 'src/data/mockData.js'));
const { AMS_GUIDE_INDEX } = await import(resolve(ROOT, 'src/data/guides/amsGuideIndex.js'));
const { OFFICIAL_QA } = await import(resolve(ROOT, 'src/data/officialQa.js'));
const { MANAGER_FAQ } = await import(resolve(ROOT, 'src/data/managerFaq.js'));

const clean = (s, n = 220) =>
  String(s == null ? '' : s).replace(/\s+/g, ' ').trim().slice(0, n);

const index = [];
const seen = new Set();
const add = (row) => {
  if (!row.id || !row.title || seen.has(row.id)) return;
  seen.add(row.id);
  index.push(row);
};

// ① 위키 가이드(GUIDES = 리치 가이드 + inquiry + cs) → /guides/{id}
for (const [id, g] of Object.entries(GUIDES)) {
  add({ id, title: clean(g.title, 200), tldr: clean(g.tldr), module: clean(g.module, 60), type: clean(g.type || 'SOP', 20), route: `/guides/${id}` });
}
// ② AMS 컨플루언스 가이드 100개(검색에서 빠져 있던) → /guides/{id}
for (const g of AMS_GUIDE_INDEX || []) {
  add({ id: g.id, title: clean(g.title, 200), tldr: clean(g.tldr), module: clean(g.module, 60), type: 'AMS가이드', route: `/guides/${g.id}` });
}
// ③ 공식 Q&A → /faq (질문=title, 답=tldr)
for (const q of OFFICIAL_QA || []) {
  add({ id: q.id, title: clean(q.q, 200), tldr: clean(q.a), module: clean(q.category, 60), type: 'Q&A', route: '/faq' });
}
// ④ 매니저 FAQ → 연결 가이드 있으면 /guides, 없으면 /faq
for (const f of MANAGER_FAQ || []) {
  add({ id: f.id, title: clean(f.q, 200), tldr: clean(f.a), module: clean(f.category, 60), type: 'FAQ', route: f.guideId ? `/guides/${f.guideId}` : '/faq' });
}

// 정적 import 가능한 ESM 모듈로 출력 → Vercel 서버리스 함수 번들에 확실히 포함됨.
const out = resolve(ROOT, 'api/_lib/guide-index.js');
mkdirSync(dirname(out), { recursive: true });
const header = '// AUTO-GENERATED by scripts/build-guide-index.mjs — 직접 수정 금지.\n'
  + '// AI 검색(api/ai-search.js)용 통합 가이드 인덱스. 콘텐츠 변경 시: npm run build:guide-index\n';
writeFileSync(out, header + 'export const GUIDE_INDEX = ' + JSON.stringify(index) + '\n', 'utf8');

const byType = index.reduce((m, g) => ((m[g.type] = (m[g.type] || 0) + 1), m), {});
console.log(`✓ api/_lib/guide-index.js — ${index.length}개`, byType);
